import AppKit
import Carbon.HIToolbox

/// Inserts text at the cursor of whatever app is frontmost by pasting it.
///
/// Pasting is the one mechanism that works in practically every text field (native, web,
/// Electron, terminals), handles any length instantly, and keeps the target app's undo intact.
/// The user's clipboard is snapshotted and restored afterwards unless they copied something
/// new in the meantime. Advanced settings › Text input can keep the dictation on the clipboard,
/// let clipboard managers record it, or type the text instead.
@MainActor
final class TextInserter {
    struct Options {
        /// Put the user's clipboard back after pasting ("Keep what I have copied").
        var restoreClipboard = true
        /// Mark the entry so clipboard managers skip it (Clipboard history off).
        var transient = true
        /// Type the text as key presses instead of pasting it (Simulate keypresses).
        var typing = false
    }

    /// How long the target app gets to read the pasteboard before the old contents return.
    /// Generous on purpose: restoring too early makes the paste silently insert stale text.
    private static let restoreDelay: Duration = .milliseconds(1000)
    /// Between typed characters: fast enough to read as streaming, slow enough that apps that
    /// process input asynchronously (Electron, terminals) keep up.
    private static let typingInterval: Duration = .milliseconds(3)

    private struct PendingRestore {
        let items: [[NSPasteboard.PasteboardType: Data]]
        let changeCount: Int
        let task: Task<Void, Never>
    }

    private var pending: PendingRestore?
    private var typing: Task<Void, Never>?

    /// Pastes or types the text; returns once it has been sent to the frontmost app.
    func insert(_ text: String, options: Options) async {
        let text = Self.spaced(text)
        guard options.typing else {
            paste(text, options: options)
            return
        }
        let previous = typing
        let task = Task {
            await previous?.value  // Back-to-back dictations type one after the other.
            await Self.type(text)
        }
        typing = task
        await task.value
    }

    /// Puts the text on the clipboard without pasting it (Paste result text off).
    func copy(_ text: String, transient: Bool) {
        pending?.task.cancel()
        pending = nil
        write(text, transient: transient)
    }

    private func paste(_ text: String, options: Options) {
        let pasteboard = NSPasteboard.general
        // Back-to-back dictations: keep the user's original clipboard, not our previous paste.
        let saved: [[NSPasteboard.PasteboardType: Data]]
        pending?.task.cancel()
        if let pending, pasteboard.changeCount == pending.changeCount {
            saved = pending.items
        } else {
            saved = Self.snapshot(pasteboard)
        }
        pending = nil

        write(text, transient: options.transient)
        let changeCount = pasteboard.changeCount
        Self.postPaste()

        guard options.restoreClipboard else { return }
        let task = Task { [weak self] in
            try? await Task.sleep(for: Self.restoreDelay)
            guard !Task.isCancelled, let self else { return }
            self.restore()
        }
        pending = PendingRestore(items: saved, changeCount: changeCount, task: task)
    }

    private func write(_ text: String, transient: Bool) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            // nspasteboard.org convention: clipboard managers should not record this entry.
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        pasteboard.writeObjects([item])
    }

    private func restore() {
        guard let pending else { return }
        self.pending = nil
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount == pending.changeCount else { return }  // User copied something new.
        pasteboard.clearContents()
        guard !pending.items.isEmpty else { return }
        pasteboard.writeObjects(
            pending.items.map { types in
                let item = NSPasteboardItem()
                for (type, data) in types { item.setData(data, forType: type) }
                return item
            })
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
    }

    // MARK: Keystroke

    private static func postPaste() {
        // Explicit flags so modifiers the user is still physically holding don't leak in
        // (e.g. Shift would turn this into "Paste and Match Style").
        postKey(CGKeyCode(pasteKeyCode()), flags: .maskCommand)
    }

    /// Return, for "Hold Shift to send": without the Shift the user may still be holding, which
    /// would make it a line break in chat apps.
    static func pressReturn() {
        postKey(CGKeyCode(kVK_Return), flags: [])
    }

    private static func postKey(_ key: CGKeyCode, flags: CGEventFlags, text: [UniChar]? = nil) {
        let source = CGEventSource(stateID: .privateState)
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: keyDown) else { continue }
            event.flags = flags
            if let text { event.keyboardSetUnicodeString(stringLength: text.count, unicodeString: text) }
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventTag)
            event.post(tap: .cghidEventTap)
        }
    }

    /// Types each character as a key press carrying the character itself, so it works with any
    /// keyboard layout.
    private static func type(_ text: String) async {
        for character in text {
            switch character {
            case "\n", "\r\n": postKey(CGKeyCode(kVK_Return), flags: [])
            case "\t": postKey(CGKeyCode(kVK_Tab), flags: [])
            default: postKey(0, flags: [], text: Array(String(character).utf16))
            }
            try? await Task.sleep(for: typingInterval)
        }
    }

    /// The virtual key that produces "v" while ⌘ is held in the current layout. Shortcuts follow
    /// the layout (Dvorak's V is not on the QWERTY V key), so a hard-coded key code would break.
    private static func pasteKeyCode() -> Int {
        let fallback = kVK_ANSI_V  // Non-Latin layouts map shortcuts to the ANSI position.
        guard let layout = KeyboardLayout.current else { return fallback }
        return (0..<128).first { layout.character(keyCode: $0, carbonModifiers: cmdKey) == "v" } ?? fallback
    }

    // MARK: Spacing

    /// Prefixes a space when the text would otherwise run into the word before the cursor,
    /// e.g. dictating a second sentence after the first. Only applied when the focused field
    /// exposes its contents through Accessibility; otherwise the text is inserted as-is.
    private static func spaced(_ text: String) -> String {
        guard let previous = characterBeforeCursor(), !previous.isWhitespace,
            !"([{<\"'“‘/@#`$".contains(previous)
        else { return text }
        return " " + text
    }

    private static func characterBeforeCursor() -> Character? {
        if NSApp.isActive {
            // One of Localflow's windows (the walkthrough's practice field): Accessibility would have
            // to answer a query to this process from this very thread.
            guard let view = NSApp.keyWindow?.firstResponder as? NSTextView else { return nil }
            let location = view.selectedRange().location
            guard location > 0 else { return "\n" }
            return (view.string as NSString).substring(with: NSRange(location: location - 1, length: 1)).first
        }
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.15)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
            let focused, CFGetTypeID(focused) == AXUIElementGetTypeID()
        else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.15)
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
            let rangeValue, CFGetTypeID(rangeValue) == AXValueGetTypeID()
        else { return nil }
        var range = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &range) else { return nil }
        guard range.location > 0 else { return "\n" }  // Start of the field.
        var previous = CFRange(location: range.location - 1, length: 1)
        guard let previousValue = AXValueCreate(.cfRange, &previous) else { return nil }
        var string: CFTypeRef?
        guard
            AXUIElementCopyParameterizedAttributeValue(
                element, kAXStringForRangeParameterizedAttribute as CFString, previousValue, &string) == .success
        else { return nil }
        return (string as? String)?.last
    }
}
